from __future__ import annotations

import os
from contextlib import contextmanager
from pathlib import Path

from .common import CollectorError


@contextmanager
def exclusive_lock(directory: Path):
    """An OS lock is automatically released after a crash; the file may remain."""
    directory.mkdir(parents=True, exist_ok=True)
    with (directory / ".collector.lock").open("a+b") as stream:
        stream.seek(0, os.SEEK_END)
        if stream.tell() == 0:
            stream.write(b"\0")
            stream.flush()
        stream.seek(0)
        try:
            if os.name == "nt":
                import msvcrt

                msvcrt.locking(stream.fileno(), msvcrt.LK_NBLCK, 1)
            else:
                import fcntl

                fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            raise CollectorError("Inny proces używa tego katalogu danych.") from exc
        try:
            yield
        finally:
            stream.seek(0)
            if os.name == "nt":
                msvcrt.locking(stream.fileno(), msvcrt.LK_UNLCK, 1)
            else:
                fcntl.flock(stream.fileno(), fcntl.LOCK_UN)
